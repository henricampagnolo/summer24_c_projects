#include "../libft.h"

t_list	*ft_lstlast(t_list *lst)
{
	t_list	*curr_node;
	int		size;
	int		i;

	if (!lst)
		return (lst);
	curr_node = lst;
	size = ft_lstsize(lst);
	i = 0;
	while (i < size - 1)
	{
		curr_node = curr_node->next;
		i++;
	}
	return (curr_node);
}