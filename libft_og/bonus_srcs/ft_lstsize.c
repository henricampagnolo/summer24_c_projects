#include "../libft.h"

int	ft_lstsize(t_list *lst)
{
	t_list	*curr_node;
	int i;

	i = 0;
	curr_node = lst;
	if (!lst)
		return (0);
	while (curr_node)
	{
		curr_node = curr_node->next;
		i++;
	}
	return (i);
}