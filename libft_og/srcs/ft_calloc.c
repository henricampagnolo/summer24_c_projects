#include "../libft.h"

void	*ft_calloc(size_t nmemb, size_t size)
{
	void	*result;

	if (nmemb * size == 0)
		return (0);
	result = malloc(nmemb * size);
	if (result == 0)
		return (0);
	ft_bzero(result, nmemb * size);
	return (result);
}
