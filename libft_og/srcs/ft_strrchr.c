#include "../libft.h"

char	*ft_strrchr(const char *s, int c)
{
	int		i;
	char	*pos;
	char	*str;

	i = 0;
	pos = 0;
	str = (char *) s;
	while (str[i] != 0)
	{
		if (str[i] == c)
			pos = str + i;
		i++;
	}
	return (pos);
}
