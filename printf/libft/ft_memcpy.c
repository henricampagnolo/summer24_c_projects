#include "libft.h"

void	*ft_memcpy(void *dest, const void *src, size_t n)
{
	char	*p_src;
	char	*p_dest;

	p_src = (char *) src;
	p_dest = (char *) dest;
	while (n > 0)
	{
		*p_dest = *p_src;
		p_src++;
		p_dest++;
		n--;
	}
	return (dest);
}
