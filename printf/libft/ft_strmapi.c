#include "libft.h"

char	*ft_strmapi(char const *s, char (*f)(unsigned int, char))
{
	char	*result;
	size_t	i;

	i = 0;
	result = ft_strdup(s);
	if (result == 0)
		return (0);
	while (i < ft_strlen(result))
	{
		result[i] = f(i, s[i]);
		i++;
	}
	return (result);
}
