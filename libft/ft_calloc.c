#include "libft.h"

void	*ft_calloc(size_t nmemb, size_t size)
{
	size_t	bytes;
	void	*result;

	bytes = nmemb * size;
	if (size && ((bytes / size) != nmemb))
		return (NULL);
	result = malloc(bytes);
	if (NULL == result)
		return (NULL);
	ft_bzero(result, bytes);
	return (result);
}
